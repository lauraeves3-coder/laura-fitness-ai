// Gramas de `amount` medidas `label` do alimento, ou null sem medida TBCA.
// Sem "cheia"/"rasa" no texto, vale a cheia; se a TBCA só tiver uma, vale essa.
export function tbcaMeasureGrams(id, label, fill = null) {
  const measures = TBCA_HOUSEHOLD_MEASURES[id];
  if (!measures) return null;
  const keys = fill ? [`${label} ${fill}`, label] : [`${label} cheia`, `${label} rasa`, label];
  const key = keys.find((candidate) => measures[candidate] != null);
  return key ? measures[key] : null;
}
